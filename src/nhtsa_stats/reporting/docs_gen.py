"""Generate the data-driven parts of the documentation from inventory outputs and code.

``docs/generated/inventory_tables.md``  archive list with checksums, table availability and
                                        row counts by source-year, integrity-check summary.
``docs/generated/harmonised_variables.md``  every harmonised analytic variable: level,
                                        timing class (leakage registry), source fields and
                                        the code mapping (from the harmonize docstrings).

Hand-written narrative documents (data_audit.md, data_dictionary.md,
variable_harmonization.md) link to these generated files so that the numeric tables can never
drift from the code that produced them.  Run with ``python -m nhtsa_stats.reporting.docs_gen``.
"""

from __future__ import annotations

import inspect

import pandas as pd

from nhtsa_stats import config
from nhtsa_stats.processing import harmonize as h

GEN_DIR = config.PROJECT_ROOT / "docs" / "generated"


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def inventory_tables() -> str:
    a = pd.read_csv(config.AUDIT_DIR / "archive_inventory.csv")
    t = pd.read_csv(config.AUDIT_DIR / "table_inventory.csv")
    out = [
        "# Generated inventory tables",
        "",
        "_Generated by `nhtsa_stats.reporting.docs_gen` from `outputs/audit/*.csv`. Do not edit by hand._",
        "",
    ]
    out += ["## Archives (36)", ""]
    a = a.assign(MB=(a["size_bytes"] / 1e6).round(1), sha256=a["sha256"].str[:16] + "…")
    out += [
        _md(a[["archive", "source", "year", "kind", "MB", "n_members", "sha256", "lfs_oid_match"]]),
        "",
    ]
    for src in ("FARS", "CRSS"):
        sub = t[t["source"] == src]
        piv = sub.pivot_table(index="table", columns="year", values="rows", aggfunc="sum")
        piv = piv.map(lambda v: "" if pd.isna(v) else f"{int(v):,}")
        piv.columns = [str(c) for c in piv.columns]
        out += [
            f"## {src}: rows per table and year (blank = table absent that year)",
            "",
            _md(piv.reset_index()),
            "",
        ]
        keys = (
            sub.groupby("table")
            .agg(
                candidate_key=("candidate_key", lambda s: " / ".join(sorted(set(s)))),
                key_unique_all_years=("key_unique", "all"),
                duplicate_rows=("duplicate_rows", "sum"),
                encodings=("encoding", lambda s: ", ".join(sorted(set(s)))),
            )
            .reset_index()
        )
        out += [f"### {src}: verified record keys", "", _md(keys), ""]
    ic_path = config.AUDIT_DIR / "integrity_checks.csv"
    if ic_path.exists():
        ic = pd.read_csv(ic_path)
        summ = (
            ic.groupby(["check"])
            .agg(
                source_years=("year", "size"),
                records_checked=("n_checked", "sum"),
                failures=("n_failed", "sum"),
                status=("status", lambda s: ",".join(sorted(set(s)))),
            )
            .reset_index()
        )
        out += ["## Relational-integrity checks (all source-years)", "", _md(summ), ""]
    return "\n".join(out)


def harmonised_variables() -> str:
    out = [
        "# Generated catalogue of harmonised analytic variables",
        "",
        "_Generated from `processing/harmonize.py` (REGISTRY and mapping docstrings). Do not edit by hand._",
        "",
        "Timing classes: `pre_crash` and `crash_circumstance` may enter severity models; `post_crash` and "
        "`outcome` may not (enforced by `assert_no_leakage`).",
        "",
    ]
    reg = pd.DataFrame(
        [
            {"variable": k, "timing": v.timing, "level": v.level, "note": v.note}
            for k, v in h.REGISTRY.items()
        ]
    ).sort_values(["timing", "variable"])
    out += ["## Leakage registry", "", _md(reg), ""]
    out += ["## Code mappings", ""]
    funcs = [
        f
        for name, f in inspect.getmembers(h, inspect.isfunction)
        if not name.startswith("_")
        and f.__module__ == h.__name__
        and name not in ("assert_no_leakage", "binary")
    ]
    for f in sorted(funcs, key=lambda f: f.__code__.co_firstlineno):
        doc = inspect.getdoc(f) or ""
        sig = str(inspect.signature(f))
        out += [f"### `{f.__name__}{sig}`", "", doc, ""]
    out += [
        "### Vehicle body groups (`BODY_TYP`)",
        "",
        _md(
            pd.DataFrame(
                [
                    {"group": g, "BODY_TYP codes": ", ".join(map(str, c))}
                    for g, c in h.BODY_GROUPS.items()
                ]
            )
        ),
        "",
    ]
    return "\n".join(out)


def processed_dictionary() -> str:
    """Column-level dictionary of the analytic datasets, read from the Parquet files."""
    import polars as pl

    out = [
        "# Generated dictionary of the analytic datasets",
        "",
        "_Generated from `data/processed/*.parquet` by `nhtsa_stats.reporting.docs_gen`. Upper-case columns are raw "
        "NHTSA fields carried through unchanged (meanings: `outputs/audit/codebook.csv`); lower-case columns are "
        "harmonised (definitions: `docs/generated/harmonised_variables.md`). Do not edit by hand._",
        "",
    ]
    for name in ("crss_crash", "crss_person", "fars_crash", "fars_person"):
        path = config.PROCESSED_DIR / f"{name}.parquet"
        if not path.exists():
            continue
        df = pl.read_parquet(path)
        out += [f"## `{name}` — {df.height:,} rows × {df.width} columns", ""]
        rows = []
        for c in df.columns:
            s = df[c]
            info = h.REGISTRY.get(c)
            if s.dtype == pl.Utf8 and s.n_unique() <= 15:
                vals = ", ".join(str(v) for v in s.drop_nulls().unique().sort().to_list())
            elif s.dtype.is_numeric() and s.null_count() < df.height:
                vals = f"{s.min()} – {s.max()}"
            else:
                vals = f"{s.n_unique():,} distinct"
            rows.append(
                {
                    "column": f"`{c}`",
                    "type": str(s.dtype),
                    "% null": round(100 * s.null_count() / df.height, 1),
                    "values": vals[:120],
                    "timing": info.timing if info else ("raw" if c.isupper() else ""),
                }
            )
        out += [_md(pd.DataFrame(rows)), ""]
    return "\n".join(out)


def run() -> dict:
    main()
    return {"generated": [str(p) for p in GEN_DIR.glob("*.md")]}


def main() -> None:
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    (GEN_DIR / "inventory_tables.md").write_text(inventory_tables())
    (GEN_DIR / "harmonised_variables.md").write_text(harmonised_variables())
    (GEN_DIR / "processed_datasets.md").write_text(processed_dictionary())


if __name__ == "__main__":
    main()
