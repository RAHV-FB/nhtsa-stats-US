"""W05 FARS-side attacks. (a) midblock 72.6% vs alternative location sources (PBTYPE PEDLOC, crash
RELJCT2/A_INTSEC); (b) hit-and-run: crash-level A_HR vs vehicle HIT_RUN vs striker-specific, per year;
(c) 'mostly dark' vs hour-of-day and vs non-ped deaths; (d) 'major urban roads': joint urban x arterial,
vs other deaths; (e) VSPD_LIM unknown share / striker-vs-other-vehicle speed limit. Read printed tables."""
import polars as pl, glob
def rd(t):
    out=[]
    for f in sorted(glob.glob(f"data/interim/FARS/{t}/*.parquet")):
        y=int(f.split('/')[-1].split('.')[0])
        out.append(pl.read_parquet(f).with_columns(pl.lit(y).alias("Y")))
    return pl.concat(out,how="diagonal_relaxed")
per=rd("person").filter(pl.col("INJ_SEV")==4).select("Y","ST_CASE","VEH_NO","PER_NO","PER_TYP","LOCATION","STR_VEH","AGE")
acc=rd("accident").select("Y","ST_CASE","LGT_COND","HOUR","RELJCT2","TYP_INT","REL_ROAD","FUNC_SYS","RUR_URB","MONTH")
aux=rd("acc_aux").select("Y","ST_CASE","A_HR","A_INTSEC","A_ROADFC","A_RU","A_TOD","A_JUNC")
veh=rd("vehicle").select("Y","ST_CASE","VEH_NO","HIT_RUN","VSPD_LIM")
pb=rd("pbtype").select("Y","ST_CASE","VEH_NO","PER_NO","PEDLOC","PEDCGP")
d=per.join(acc,on=["Y","ST_CASE"],how="left").join(aux,on=["Y","ST_CASE"],how="left")
ped=d.filter(pl.col("PER_TYP")==5).join(pb,on=["Y","ST_CASE","VEH_NO","PER_NO"],how="left")
N=ped.height; print("ped deaths",N)
print("== (a) LOCATION midblock",ped.filter(pl.col("LOCATION").is_in([10,11,13,16])).height/N)
print("LOCATION 16 (bike lane) n",ped.filter(pl.col("LOCATION")==16).height, " code 10 (marked crosswalk away from int) n",ped.filter(pl.col("LOCATION")==10).height)
print("excl. 10 & 16:",ped.filter(pl.col("LOCATION").is_in([11,13])).height/N)
print("PEDLOC dist"); print(ped.group_by("PEDLOC").len().sort("PEDLOC"))
print("crosstab LOCATION-group x PEDLOC");
g=ped.with_columns(pl.when(pl.col("LOCATION").is_in([1,2,3,9])).then(pl.lit("int")).when(pl.col("LOCATION").is_in([10,11,13,16])).then(pl.lit("mid")).otherwise(pl.lit("oth")).alias("lg"))
print(g.group_by("lg","PEDLOC").len().sort("lg","PEDLOC"))
print("A_INTSEC dist (1=intersection?)"); print(ped.group_by("A_INTSEC").len().sort("A_INTSEC"))
print("RELJCT2 dist"); print(ped.group_by("RELJCT2").len().sort("RELJCT2"))
print("TYP_INT"); print(ped.group_by("TYP_INT").len().sort("TYP_INT"))
print("by year share RELJCT2==1 (non-junction)"); print(ped.group_by("Y").agg((pl.col("RELJCT2")==1).mean().alias("nonjunc"),(pl.col("A_INTSEC")==1).mean().alias("a_int1"),(pl.col("A_INTSEC")==2).mean().alias("a_int2")).sort("Y"))
print("== (b) hit and run")
print("A_HR dist among ped deaths");print(ped.group_by("A_HR").len().sort("A_HR"))
print("A_HR==1 share",(ped["A_HR"]==1).mean())
hrv=veh.group_by("Y","ST_CASE").agg((pl.col("HIT_RUN")>0).any().alias("veh_hr_any"), pl.col("HIT_RUN").max().alias("mx"))
print("vehicle HIT_RUN values");print(veh.group_by("HIT_RUN").len().sort("HIT_RUN"))
p2=ped.join(hrv,on=["Y","ST_CASE"],how="left")
print("vehicle-level any HIT_RUN>0 share",(p2["veh_hr_any"]).mean())
strv=veh.rename({"VEH_NO":"STR_VEH","HIT_RUN":"STR_HR","VSPD_LIM":"STR_VSPD"})
p3=p2.join(strv,on=["Y","ST_CASE","STR_VEH"],how="left")
print("STR_VEH dist (0/null/99?)");print(p3.group_by(pl.col("STR_VEH").clip(0,99)).len().sort("STR_VEH").head(8))
print("striker HIT_RUN>0 share (of all)",(p3["STR_HR"]>0).mean()," striker not linked share",p3["STR_HR"].is_null().mean())
print("A_HR=1 by striker-linkage"); print(p3.group_by(p3["STR_HR"].is_null().alias("striker_unlinked")).agg(pl.len(),(pl.col("A_HR")==1).mean()))
print("hit-run by year");print(p3.group_by("Y").agg((pl.col("A_HR")==1).mean().alias("hr"),pl.len()).sort("Y"))
nonped=d.filter(~pl.col("PER_TYP").is_in([5]))
print("non-ped deaths A_HR share",(nonped["A_HR"]==1).mean())
print("== (c) light")
print("ped dark share (LGT 2,3,6)",ped["LGT_COND"].is_in([2,3,6]).mean(),"daylight",(ped["LGT_COND"]==1).mean())
print("nonped dark",nonped["LGT_COND"].is_in([2,3,6]).mean(),"daylight",(nonped["LGT_COND"]==1).mean())
print("ped dark by month share");print(ped.group_by("MONTH").agg(pl.col("LGT_COND").is_in([2,3,6]).mean().alias("dark"),pl.len()).sort("MONTH"))
print("ped by hour (share of ped deaths) vs nonped");
h=ped.group_by("HOUR").len().sort("HOUR").with_columns((pl.col("len")/N).alias("ped"))
h2=nonped.group_by("HOUR").len().sort("HOUR").with_columns((pl.col("len")/nonped.height).alias("nonped"))
print(h.join(h2,on="HOUR").select("HOUR","ped","nonped"))
print("dark & HOUR 17-20 (dusk-ish evening) share", ped.filter(pl.col("LGT_COND").is_in([2,3,6])).filter(pl.col("HOUR").is_between(16,20)).height/N)
print("== (d) road class / urban")
print("ped FUNC_SYS");print(ped.group_by("FUNC_SYS").len().sort("FUNC_SYS"))
print("ped A_ROADFC share"); print(ped.group_by("A_ROADFC").len().sort("A_ROADFC").with_columns(pl.col("len")/N))
print("nonped A_ROADFC share"); print(nonped.group_by("A_ROADFC").len().sort("A_ROADFC").with_columns(pl.col("len")/nonped.height))
ped=ped.with_columns((pl.col("A_RU")==2).alias("urb"),pl.col("A_ROADFC").is_in([3,4]).alias("art"))
print("urban & arterial",ped.filter(pl.col("urb")&pl.col("art")).height/N,"urban & principal arterial",ped.filter(pl.col("urb")&(pl.col("A_ROADFC")==3)).height/N, "urban & (interstate..minor art)",ped.filter(pl.col("urb")&pl.col("A_ROADFC").is_in([1,2,3,4])).height/N)
print("urban share nonped",(nonped["A_RU"]==2).mean())
print("== (e) VSPD_LIM")
print(p3.group_by("STR_VSPD").len().sort("STR_VSPD"))
# speed limit of striker vs max/min across crash
vmax=veh.filter((pl.col("VSPD_LIM")>0)&(pl.col("VSPD_LIM")<98)).group_by("Y","ST_CASE").agg(pl.col("VSPD_LIM").min().alias("vmin"),pl.col("VSPD_LIM").max().alias("vmax"))
p4=p3.join(vmax,on=["Y","ST_CASE"],how="left")
print("striker limit unknown/0/98+ share",(p4["STR_VSPD"].is_null()|(p4["STR_VSPD"]<=0)|(p4["STR_VSPD"]>=98)).mean())
print("crash limit disagrees across vehicles share (known)",(p4["vmin"]!=p4["vmax"]).sum()/p4["vmin"].is_not_null().sum())
print("striker unknown but another vehicle known",((p4["STR_VSPD"].is_null()|(p4["STR_VSPD"]<=0)|(p4["STR_VSPD"]>=98))&p4["vmax"].is_not_null()).sum())
print("speed-limit unknown share by year");print(p4.group_by("Y").agg((pl.col("STR_VSPD").is_null()|(pl.col("STR_VSPD")<=0)|(pl.col("STR_VSPD")>=98)).mean().alias("unk")).sort("Y"))
