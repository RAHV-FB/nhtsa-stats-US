import sys; sys.path.insert(0, "scripts/audit")
from helpers import *
df = aux_main("FARS", "per", ["A_HRACE", "A_RCAT", "A_HISP"], ["RACE", "HISPANIC", "INJ_SEV"])
r = load_table("FARS", "race", years=list(range(2019, 2025)), columns=["ST_CASE", "VEH_NO", "PER_NO", "RACE", "ORDER", "MULTRACE"]).unique()
rs = r.group_by(["YEAR", "ST_CASE", "VEH_NO", "PER_NO"]).agg(pl.len().alias("nrace"), pl.col("RACE").first().alias("R1"), pl.col("MULTRACE").max().alias("MR"))
df = df.join(rs, on=["YEAR", "ST_CASE", "VEH_NO", "PER_NO"], how="left")
df = df.with_columns(pl.when(pl.col("YEAR") <= 2018).then(pl.col("RACE")).when((pl.col("nrace") > 1) | (pl.col("MR") == 1)).then(pl.lit(500)).otherwise(pl.col("R1")).alias("RACEX"))
print("race rows missing for 2019+:", df.filter((pl.col("YEAR") >= 2019) & pl.col("nrace").is_null()).height)
print(wide(df, "A_RCAT", "RACEX", "FARS", "race"))
print(wide(df.filter(pl.col("YEAR")<=2018), "A_RCAT", "RACEX", "FARS", "person"))
print(df.group_by(["A_HRACE", "A_HISP", "A_RCAT"]).agg(pl.len()).sort(["A_HRACE", "A_HISP", "A_RCAT"]))
